import AppKit
import Carbon.HIToolbox

/// Inserts text into the focused field by pasting, then puts the user's clipboard back.
@MainActor
final class TextInserter {
    /// Types that well-behaved clipboard managers skip (see nspasteboard.org).
    private static let transientTypes: [NSPasteboard.PasteboardType] = [
        .init("org.nspasteboard.TransientType"),
        .init("org.nspasteboard.AutoGeneratedType"),
    ]

    func insert(_ text: String) async {
        let pasteboard = NSPasteboard.general
        let saved = snapshot(pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        for type in Self.transientTypes { item.setData(Data(), forType: type) }
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        postCommandV()

        // Give the target app time to read the clipboard before restoring it.
        try? await Task.sleep(for: .milliseconds(400))
        // If something else wrote to the clipboard meanwhile, leave it alone.
        guard pasteboard.changeCount == ourChangeCount else { return }
        restore(saved, to: pasteboard)
    }

    /// Copies text to the clipboard normally (for "copy from history").
    func copy(_ text: String) {
        NSPasteboard.general.clearContents()
        NSPasteboard.general.setString(text, forType: .string)
    }

    private func postCommandV() {
        let source = CGEventSource(stateID: .hidSystemState)
        let keyCode = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: keyCode, keyDown: false)
        // Exactly ⌘ — not whatever modifiers (e.g. Fn) happen to be held.
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }

    private func snapshot(_ pasteboard: NSPasteboard) -> [[NSPasteboard.PasteboardType: Data]] {
        (pasteboard.pasteboardItems ?? []).map { item in
            var types: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { types[type] = data }
            }
            return types
        }
    }

    private func restore(_ saved: [[NSPasteboard.PasteboardType: Data]], to pasteboard: NSPasteboard) {
        pasteboard.clearContents()
        guard !saved.isEmpty else { return }
        let items = saved.map { types in
            let item = NSPasteboardItem()
            for (type, data) in types { item.setData(data, forType: type) }
            return item
        }
        pasteboard.writeObjects(items)
    }
}
