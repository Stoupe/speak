#!/bin/zsh
# Builds a shareable, notarized Speak.zip.
#
#   Tools/release.sh --dry-run [--version 0.3] [--build 7] [--feed URL --update-key KEY]
#       Archive + export signed with your local Apple Development certificate, then run the same checks
#       notarization cares about. Nothing is sent to Apple and no certificates are created.
#       --feed/--update-key turn on Sparkle updates in the build (Tools/update-test.sh uses this).
#
#   Tools/release.sh [--version 0.3] [--notary-profile speak-notary] [--publish [--notes FILE]]
#       The real thing: Developer ID signing (Xcode may create a cloud-managed Developer ID certificate on
#       first use), notarization, stapling, the final zip and the Sparkle appcast. Asks before contacting Apple.
#       Runs only on main, clean and level with origin/main, so the release matches a merged commit.
#       Without --publish nothing is uploaded: it prints the publishing steps at the end.
#       --publish then asks once more and does them: a GitHub release tagged vX.Y on the built commit (notes
#       from FILE, else generated by GitHub), a check that the download works, and a PR that updates
#       site/appcast.xml, merged straight away (or set to auto-merge), which deploys the feed.
#
#   Tools/release.sh --version 0.3 --resume [--publish [--notes FILE]]
#       Picks up after notarization outlasted the script's 30 min wait: waits for the same submission again,
#       then staples, packages, updates the appcast and (with --publish) publishes the build made earlier.
#
# One-time setup for real releases: store notarization credentials in your Keychain, e.g.
#   xcrun notarytool store-credentials speak-notary --apple-id you@example.com --team-id V4TSTMTS4F
# (prompts for an app-specific password from account.apple.com; the script only uses the profile name).

set -euo pipefail
cd "$(dirname "$0")/.."

TEAM_ID="V4TSTMTS4F"
DRY_RUN=false
PUBLISH=false
RESUME=false
NOTES=""
VERSION=""
BUILD=""
NOTARY_PROFILE="speak-notary"

# Sparkle updates. Real releases refuse to run until all three are set, and builds without them never check for
# updates (see Speak/App/Updater.swift). Every release keeps its feed URL forever, so it must keep working: a
# custom domain added to GitHub Pages later redirects from the github.io address.
FEED_URL="https://stoupe.github.io/speak/appcast.xml"         # published from site/appcast.xml
UPDATE_KEY="PFlseSBc4KrnvY+QuYNdbd5iJ2MMhkNQBJR2VPyM57I="     # public EdDSA key: generate_keys -p (private key: Keychain, backup in 1Password)
DOWNLOADS_URL="https://github.com/Stoupe/speak/releases/download"  # the release tag is appended

while (( $# )); do
    case "$1" in
        --dry-run) DRY_RUN=true ;;
        --publish) PUBLISH=true ;;
        --resume) RESUME=true ;;
        --notes) NOTES="$2"; shift ;;
        --version) VERSION="$2"; shift ;;
        --build) BUILD="$2"; shift ;;
        --feed) FEED_URL="$2"; shift ;;
        --update-key) UPDATE_KEY="$2"; shift ;;
        --notary-profile) NOTARY_PROFILE="$2"; shift ;;
        *) echo "Unknown option: $1" >&2; exit 2 ;;
    esac
    shift
done

step() { print -P "\n%B==> $1%b"; }
fail() { print -P "%F{red}✗ $1%f" >&2; exit 1; }
ok() { print -P "%F{green}✓%f $1"; }
warn() { print -P "%F{yellow}!%f $1"; }
# Asks on the terminal; without one (e.g. run from another tool), reads a line from stdin.
confirm() {
    local reply
    if [[ -t 0 ]]; then read -q "reply?$1 [y/N] " || { print; return 1; }; print
    else print -n "$1 [y/N] "; read -r reply || return 1; print "$reply"; [[ "$reply" == [yY]* ]]
    fi
}

$DRY_RUN && { $PUBLISH || $RESUME; } && fail "--dry-run can't be combined with --publish or --resume."
[[ -z "$NOTES" ]] || $PUBLISH || fail "--notes only applies with --publish."
[[ -z "$NOTES" || -f "$NOTES" ]] || fail "No release notes at $NOTES."

# Version: given, or the project's MARKETING_VERSION.
if [[ -z "$VERSION" ]]; then
    $RESUME && fail "--resume needs --version, to find the earlier build."
    VERSION=$(xcodebuild -project Speak.xcodeproj -target Speak -configuration Release -showBuildSettings 2>/dev/null \
        | awk -F' = ' '/ MARKETING_VERSION / { print $2; exit }')
fi
TAG="v$VERSION"

# Build number: the commit count on main. It only grows (main can't be force-pushed), whatever the merge style.
# A resumed release reuses the build, commit and notarization submission recorded by the first run.
if $RESUME; then
    RECORDS=( build/release/Speak-$VERSION-*/submission-id(Nom) )
    (( ${#RECORDS} )) || fail "No earlier $VERSION build waiting on notarization in build/release."
    OUT="${RECORDS[1]:h}"
    BUILD="${OUT##*-}"
    COMMIT=$(<"$OUT/commit")
    SUBMISSION_ID=$(<"$OUT/submission-id")
else
    [[ -n "$BUILD" ]] || BUILD=$(git rev-list --count HEAD)
    OUT="build/release/Speak-$VERSION-$BUILD"
    COMMIT=$(git rev-parse HEAD)
fi

# A real release must match a merged commit, and its appcast PR is cut from here.
problems=()
[[ -z "$(git status --porcelain)" ]] || problems+=("Uncommitted changes.")
[[ "$(git branch --show-current)" == main ]] || problems+=("Not on main.")
if ! $RESUME; then
    git fetch -q origin main 2>/dev/null || problems+=("Couldn't fetch origin/main.")
    [[ "$COMMIT" == "$(git rev-parse origin/main 2>/dev/null)" ]] \
        || problems+=("Not level with origin/main (pull, or push your work through a PR first).")
fi
for problem in $problems; do
    if $DRY_RUN; then warn "$problem (fine for a dry run)"; else fail "$problem"; fi
done

# Sparkle only offers a build whose number is higher than the installed one.
NEWEST=$(sed -n 's:.*<sparkle\:version>\([0-9]*\)</sparkle\:version>.*:\1:p' site/appcast.xml 2>/dev/null | sort -n | tail -1)
if (( BUILD <= ${NEWEST:-0} )); then
    message="Build $BUILD isn't higher than $NEWEST, the newest in site/appcast.xml: Sparkle would never offer it."
    if $DRY_RUN; then warn "$message (fine for a dry run)"; else fail "$message"; fi
fi

if $PUBLISH; then
    gh auth status >/dev/null 2>&1 || fail "gh isn't signed in to GitHub (gh auth login)."
    [[ -z "$(git ls-remote --tags origin "refs/tags/$TAG")" ]] || fail "$TAG already exists on GitHub."
fi

if $DRY_RUN; then
    print "Dry run: Speak $VERSION ($BUILD). Nothing will be sent to Apple."
else
    [[ -n "$FEED_URL" && -n "$UPDATE_KEY" && -n "$DOWNLOADS_URL" ]] \
        || fail "Updates aren't set up: fill in FEED_URL, UPDATE_KEY and DOWNLOADS_URL at the top of this script."
    if $RESUME; then
        print "Resuming: Speak $VERSION ($BUILD) from ${COMMIT[1,7]}, notarization submission $SUBMISSION_ID."
    else
        print "Release: Speak $VERSION ($BUILD) from ${COMMIT[1,7]}."
        print "This will contact Apple to sign with Developer ID (creating a certificate on first use) and to notarize."
    fi
    $PUBLISH && print "Afterwards it asks again before publishing $TAG on GitHub."
    confirm "Continue?" || exit 1
    xcrun notarytool history --keychain-profile "$NOTARY_PROFILE" >/dev/null 2>&1 \
        || fail "No notarization credentials named '$NOTARY_PROFILE'. See the setup note at the top of this script."
fi

# Build, check and submit. Skipped by --resume; not indented, as it is most of the script.
if ! $RESUME; then
rm -rf "$OUT"
mkdir -p "$OUT"
print "$COMMIT" > "$OUT/commit"

step "Archiving"
xcodebuild archive \
    -project Speak.xcodeproj -scheme Speak -configuration Release \
    -destination "generic/platform=macOS" \
    -archivePath "$OUT/Speak.xcarchive" \
    MARKETING_VERSION="$VERSION" CURRENT_PROJECT_VERSION="$BUILD" \
    SPEAK_FEED_URL="$FEED_URL" SPEAK_UPDATE_KEY="$UPDATE_KEY" \
    -quiet
ok "Archived to $OUT/Speak.xcarchive"

step "Exporting"
EXPORT_OPTIONS="$OUT/ExportOptions.plist"
if $DRY_RUN; then
    # Same pipeline, but signed with the local development certificate: no network, no new certificates.
    cat > "$EXPORT_OPTIONS" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>method</key><string>debugging</string>
    <key>signingStyle</key><string>manual</string>
    <key>signingCertificate</key><string>Apple Development</string>
    <key>teamID</key><string>$TEAM_ID</string>
</dict></plist>
EOF
    xcodebuild -exportArchive -archivePath "$OUT/Speak.xcarchive" -exportPath "$OUT/export" \
        -exportOptionsPlist "$EXPORT_OPTIONS" -quiet
else
    cat > "$EXPORT_OPTIONS" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0"><dict>
    <key>method</key><string>developer-id</string>
    <key>signingStyle</key><string>automatic</string>
    <key>teamID</key><string>$TEAM_ID</string>
    <key>destination</key><string>export</string>
</dict></plist>
EOF
    xcodebuild -exportArchive -archivePath "$OUT/Speak.xcarchive" -exportPath "$OUT/export" \
        -exportOptionsPlist "$EXPORT_OPTIONS" -allowProvisioningUpdates -quiet
fi
APP="$OUT/export/Speak.app"
[[ -d "$APP" ]] || fail "Export didn't produce Speak.app"
ok "Exported $APP"

step "Checking the signature"
codesign --verify --deep --strict "$APP" || fail "Signature doesn't verify"
ok "Signature verifies (deep, strict)"
SIGNATURE=$(codesign -dvv "$APP" 2>&1)
ENTITLEMENTS=$(codesign -d --entitlements - --xml "$APP" 2>/dev/null)
[[ "$SIGNATURE" == *"flags=0x10000(runtime)"* ]] || fail "Hardened Runtime is off (required for notarization)"
ok "Hardened Runtime on"
[[ "$ENTITLEMENTS" == *"com.apple.security.device.audio-input"* ]] || fail "Missing the microphone entitlement"
ok "Microphone entitlement present"
INFO="$APP/Contents/Info.plist"
[[ "$(plutil -extract SUFeedURL raw -o - "$INFO")" == "$FEED_URL" ]] || fail "SUFeedURL doesn't match FEED_URL"
[[ "$(plutil -extract SUPublicEDKey raw -o - "$INFO")" == "$UPDATE_KEY" ]] || fail "SUPublicEDKey doesn't match UPDATE_KEY"
if [[ -n "$FEED_URL" ]]; then ok "Updates on: $FEED_URL"; else print -P "%F{yellow}!%f Updates off (no feed URL)"; fi
[[ "$SIGNATURE" == *"Timestamp="* ]] || print -P "%F{yellow}!%f No secure timestamp (expected for a dry run; Developer ID export adds one)"
if $DRY_RUN; then
    [[ "$ENTITLEMENTS" == *"get-task-allow"* ]] && print -P "%F{yellow}!%f Debug entitlement present (expected for a dry run; Developer ID export removes it)"
    print "$SIGNATURE" | grep -E -m2 "^(Authority=Apple Development|TeamIdentifier)" | sed 's/^/  /'
    step "Dry run complete"
    print "Everything up to Developer ID signing works. For the real release:"
    print "  1. One time: xcrun notarytool store-credentials $NOTARY_PROFILE --apple-id <your Apple ID> --team-id $TEAM_ID"
    print "  2. From main, level with origin/main: Tools/release.sh --version $VERSION --publish [--notes FILE]"
    exit 0
fi

[[ "$SIGNATURE" == *"Authority=Developer ID Application"* ]] || fail "Not signed with Developer ID"
ok "Signed with Developer ID"
[[ "$ENTITLEMENTS" != *"get-task-allow"* ]] || fail "Debug entitlement still present (notarization would reject it)"
ok "No debug entitlement"

step "Submitting for notarization"
SUBMISSION="$OUT/Speak-notarize.zip"
ditto -c -k --keepParent "$APP" "$SUBMISSION"
SUBMITTED="$OUT/notary-submit.json"
xcrun notarytool submit "$SUBMISSION" --keychain-profile "$NOTARY_PROFILE" --output-format json > "$SUBMITTED" \
    || fail "Couldn't submit for notarization."
SUBMISSION_ID=$(plutil -extract id raw -o - "$SUBMITTED" 2>/dev/null) || fail "No submission id from notarytool."
# Recorded so --resume can pick this submission up if it outlasts the wait below.
print "$SUBMISSION_ID" > "$OUT/submission-id"
ok "Submitted ($SUBMISSION_ID)"
fi  # ! $RESUME

APP="$OUT/export/Speak.app"
[[ -d "$APP" ]] || fail "No exported app at $APP"

step "Waiting for notarization (usually a few minutes)"
RESULT="$OUT/notary-result.json"
xcrun notarytool wait "$SUBMISSION_ID" --keychain-profile "$NOTARY_PROFILE" --timeout 30m \
    --output-format json > "$RESULT" || true
STATUS=$(plutil -extract status raw -o - "$RESULT" 2>/dev/null || echo "unknown")
if [[ "$STATUS" != "Accepted" ]]; then
    if [[ "$STATUS" == "In Progress" || "$STATUS" == "unknown" ]]; then
        resume="Tools/release.sh --version $VERSION --resume"
        $PUBLISH && resume+=" --publish"
        [[ -n "$NOTES" ]] && resume+=" --notes $NOTES"
        fail "Notarization is still $STATUS after 30 min. Check with: xcrun notarytool info $SUBMISSION_ID --keychain-profile $NOTARY_PROFILE
  Once it says Accepted, finish with: $resume"
    fi
    xcrun notarytool log "$SUBMISSION_ID" --keychain-profile "$NOTARY_PROFILE" "$OUT/notary-log.json" || true
    fail "Notarization status: $STATUS. Details: $OUT/notary-log.json"
fi
ok "Notarized (submission $SUBMISSION_ID)"

step "Stapling"
xcrun stapler staple "$APP"
GATEKEEPER=$(spctl --assess --type execute --verbose "$APP" 2>&1) || fail "Gatekeeper rejects the app: $GATEKEEPER"
[[ "$GATEKEEPER" == *"Notarized Developer ID"* ]] || fail "Gatekeeper doesn't see it as notarized: $GATEKEEPER"
ok "Gatekeeper accepts it as Notarized Developer ID"

step "Packaging"
ZIP="$OUT/Speak-$VERSION.zip"
ditto -c -k --keepParent "$APP" "$ZIP"
ok "Ready to share: $ZIP"

# Every release's zip is kept in build/updates so generate_appcast can build delta updates against them. It reuses
# the appcast in that folder, adding the new version; site/appcast.xml is the published copy.
step "Updating the appcast"
UPDATES="build/updates"
mkdir -p "$UPDATES"
cp "$ZIP" "$UPDATES/"
[[ -f "$UPDATES/appcast.xml" ]] || [[ ! -f site/appcast.xml ]] || cp site/appcast.xml "$UPDATES/appcast.xml"
SPARKLE_BIN="build/DerivedData/SourcePackages/artifacts/sparkle/Sparkle/bin"
[[ -x "$SPARKLE_BIN/generate_appcast" ]] \
    || xcodebuild -resolvePackageDependencies -project Speak.xcodeproj -scheme Speak -derivedDataPath build/DerivedData -quiet
"$SPARKLE_BIN/generate_appcast" --download-url-prefix "$DOWNLOADS_URL/$TAG/" "$UPDATES" \
    || fail "generate_appcast failed (it signs with the private key in your Keychain)"
cp "$UPDATES/appcast.xml" site/appcast.xml
ok "site/appcast.xml now lists $VERSION ($BUILD)"

# Every file the appcast serves from this release's tag: the zip, plus any deltas generate_appcast made.
ASSETS=( ${(f)"$(grep -o "$DOWNLOADS_URL/$TAG/[^\"]*" site/appcast.xml | sort -u)"} )
ASSETS=( "$UPDATES/"${^ASSETS:t} )
for asset in $ASSETS; do [[ -f "$asset" ]] || fail "The appcast points at $asset:t, which isn't in $UPDATES."; done
ZIP_URL="$DOWNLOADS_URL/$TAG/Speak-$VERSION.zip"
(( ${ASSETS[(I)*/Speak-$VERSION.zip]} )) || fail "site/appcast.xml doesn't list Speak-$VERSION.zip under $TAG."

if ! $PUBLISH; then
    step "Publish (in this order)"
    print "  1. Create a GitHub release tagged $TAG on commit $COMMIT and upload:"
    for asset in $ASSETS; do print "       $asset"; done
    print "  2. Check the download link works: $ZIP_URL"
    print "  3. Merge a PR with the new site/appcast.xml. Installed copies see the update once the site is live."
    print "  (Or start over with --publish to have this script do it.)"
    exit 0
fi

# The order matters: the feed must not go live before its download exists.
step "Publishing $TAG"
print "Release $TAG on ${COMMIT[1,7]} with: ${ASSETS:t}"
confirm "Publish it on GitHub and update the feed?" || fail "Stopped before publishing. site/appcast.xml is updated but uncommitted; finish the steps by hand or discard it."
if [[ -n "$NOTES" ]]; then NOTES_ARGS=( --notes-file "$NOTES" ); else NOTES_ARGS=( --generate-notes ); fi
gh release create "$TAG" $ASSETS --target "$COMMIT" --title "Speak $VERSION" $NOTES_ARGS \
    || fail "Couldn't create the GitHub release."
ok "Released $TAG"

for attempt in {1..12}; do
    curl -fsIL -o /dev/null "$ZIP_URL" && break
    (( attempt < 12 )) || fail "$ZIP_URL doesn't download. The feed is not updated: fix the release, then merge site/appcast.xml by hand."
    sleep 5
done
ok "Download works: $ZIP_URL"

BRANCH="release/$TAG-appcast"
git switch -q -c "$BRANCH"
git add site/appcast.xml
git commit -q -m "Release $VERSION: update feed"
git push -q -u origin "$BRANCH"
PR=$(gh pr create --head "$BRANCH" --base main --title "Release $VERSION: update feed" \
    --body "Adds Speak $VERSION (build $BUILD) to the Sparkle feed. Opened by \`Tools/release.sh --publish\` after the [$TAG release](https://github.com/Stoupe/speak/releases/tag/$TAG) was uploaded and its download checked.")
ok "Opened $PR"
# If main requires checks, merging now is refused: let GitHub merge it once they pass.
if gh pr merge "$PR" --merge --delete-branch; then
    ok "Merged: the Pages workflow deploys the feed in a minute or two"
else
    gh pr merge "$PR" --merge --auto --delete-branch || fail "Couldn't merge or auto-merge $PR; merge it by hand."
    warn "Auto-merge is on: the feed goes live when $PR merges"
fi
git switch -q main
git pull -q --ff-only
